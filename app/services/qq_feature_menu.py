def requested_topic(text: str) -> tuple[str, ...]:
    value = re.sub(r"[\s/，,。！？!?：:]", "", str(text)).casefold()
    # Anchored help requests must not hijack song titles, questions about a
    # feature's output, or a quoted remark containing the word "menu".
    match = re.fullmatch(
        r"(?:请|麻烦)?(?:给我|发我|看看|查看)?(看视频|网易云|一起听|听歌|音乐|视频|识图|图片|唱歌|语音|记忆|牌谱|群报|炉石传说|炉石|卡组|查卡|查询卡[牌片]|卡[牌片]查询|竞技场|选牌|选卡)"
        r"(?:帮助|用法|说明|菜单|怎么用)", value,
    )
    if match and match[1] in {"查询卡牌", "查询卡片", "卡牌查询", "卡片查询"}:
        return _TOPICS["查卡"]
    return _TOPICS.get(match[1], ()) if match else ()


def select_text_groups(groups, text: str):
    wanted = requested_topic(text)
    if not wanted:
        return groups
    selected = tuple((title, lines) for title, lines in groups if title in wanted)
    return selected or (("功能说明", ("当前会话没有启用这项功能，可发送“文字版菜单”查看可用入口",)),)


